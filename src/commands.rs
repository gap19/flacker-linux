use crate::model::{Repeat, Track};
use std::path::PathBuf;
#[derive(Clone, Debug, PartialEq)]
pub enum View {
    Albums,
    Artists,
    Tracks,
    Favorites,
    Recent,
    Now,
    Album(String),
    Artist(String),
}
#[derive(Clone, Debug)]
pub enum Command {
    View(View),
    Search(String),
    Play(Vec<Track>, usize),
    Append(Vec<Track>),
    PlayNext(Vec<Track>),
    UndoRemove,
    RandomAlbum,
    Collection(crate::collection::Filter),
    Preference(String, String),
    Inspector(Box<Track>),
    Presentation,
    GalleryPage(PathBuf, String),
    ClearHistory,
    Toggle,
    Pause,
    Resume,
    Stop,
    Next,
    Previous,
    Seek(f64),
    SeekRelative(f64),
    Jump(usize),
    Volume(f64),
    Shuffle(bool),
    Repeat(Repeat),
    Favorite,
    ToggleFavorite(PathBuf),
    Scan,
    CancelScan,
    AddFolder,
    Root(PathBuf),
    RemoveRoot(PathBuf),
    OpenFiles,
    OpenPaths(Vec<PathBuf>),
    /// Tracks resolved off the interface thread for `OpenPaths`, with per-file problems.
    Opened(u64, Vec<Track>, Vec<String>),
    SavePlaylist,
    SaveNamedPlaylist(String),
    QueueMove(usize, usize),
    QueueRemove(usize),
    Preferences,
    Theme(String),
    ReplayGain(String),
    Notifications(bool),
    Embedded(bool),
    OpenExternal(PathBuf),
    Extras(PathBuf),
    About,
    Quit,
    Raise,
}
